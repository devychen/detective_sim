def extract_believed_murderer(response: str) -> str:
    """
    Extract the murderer name from an agent's response.

    This function looks for a strict linguistic pattern:
        "I believe the murderer is XXX"

    Rationale (research-oriented):
    -------------------------------
    By forcing all agents to express their hypothesis using an identical surface
    form, we enable:
    - Automatic extraction without semantic parsing
    - Consistent comparison across agents and turns
    - Clean quantitative analysis of agreement / disagreement

    Parameters
    ----------
    response : str
        The full text response generated by an agent.

    Returns
    -------
    str
        The extracted murderer name if present, otherwise an empty string.
    """
    text = response.strip()
    key = "i believe the murderer is "
    idx = text.lower().find(key)
    if idx != -1:
        name = text[idx + len(key):].split()[0]
        return name.strip("：:,.!? ")
    return ""


def clean_response(speaker: str, response: str) -> str:
    """
    Clean the raw LLM output so that it contains only the current agent's utterance.

    This function performs two main sanitization steps:
    1. Removes redundant speaker prefixes (e.g., "Holmes: Holmes: ...")
    2. Truncates the response if the model starts generating other agents' lines

    Rationale:
    ----------
    LLMs sometimes simulate multi-speaker dialogue even when instructed not to.
    This function enforces a strict one-speaker-per-turn protocol, which is
    critical for clean dialogue logs and turn-based analysis.

    Parameters
    ----------
    speaker : str
        The current agent's name ("Holmes", "Marple", or "Poirot").
    response : str
        The raw text returned by the LLM.

    Returns
    -------
    str
        A cleaned version of the response containing only the current speaker's text.
    """
    text = response.strip()

    # remove repeated speaker prefix at the start
    lowers = text.lower()
    while lowers.startswith(speaker.lower() + ":"):
        text = text[len(speaker) + 1:].strip()
        lowers = text.lower()

    # truncate if response contains another agent's name
    for other in ["Holmes", "Marple", "Poirot"]:
        if other != speaker:
            idx = text.find(other + ":")
            if idx != -1:
                text = text[:idx].strip()
    return text


