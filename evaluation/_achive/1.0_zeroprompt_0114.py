"""
1.0_zeroprompt.py

本版本使用llama。gpt版本见test > test_allcases.py
同时这个版本包含分析的内容，而非直接输出结果


Purpose
-------
This script performs a *zero-shot solvability verification* for all murder cases
used in the multi-agent experiment.

Specifically, it uses a single, non-role-based Large Language Model (LLM)
to analyse each case independently, without:
- character role-play,
- multi-agent interaction,
- dialogue history,
- information asymmetry.

The goal is NOT to optimise performance, but to verify that:
1. Each case is internally coherent.
2. The provided evidence is sufficient to support a reasoned inference.
3. A competent, general-purpose LLM can arrive at a plausible conclusion
   using only the case materials.

In the broader research design, this script serves as a *baseline sanity check*
and supports the claim that failures in the multi-agent setting are not caused
by ill-posed or unsolvable cases.
"""

import os
from dotenv import load_dotenv
import yaml
from datetime import datetime
import requests

# Set NVIDIA API key
load_dotenv('nvidia_key_3b.env')
API_URL = "https://integrate.api.nvidia.com/v1"
MODEL_NAME = "meta/llama-3.2-3b-instruct"
API_KEY = os.getenv("NVIDIA_API_KEY")




# =================================================
# Case Loading
# =================================================

def load_case_files():
    """
    Load and parse all murder case files.

    This function assumes a fixed set of cases stored as:
        cases/case1.yaml
        cases/case2.yaml
        cases/case3.yaml

    Each file is expected to contain a top-level 'case' field.

    Returns
    -------
    list of dict
        A list where each element is the structured data
        for one murder case.
    """
    # read environment variable
    run_cases_env = os.getenv("RUN_CASES")

    if run_cases_env:
        # Convert "1,3" -> [1, 3]
        # RUN_CASES=1,3 python script.py
        case_ids = [int(x.strip()) for x in run_cases_env.split(",")]
    else:
        # default: load all three cases
        case_ids = [1, 2, 3]

    cases = []
    for i in case_ids:
        file_path = os.path.join('cases', f'case{i}.yaml')
        if not os.path.exists(file_path):
            print(f"WARNING: case file {file_path} does not exist. Skipping.")
            continue
        with open(file_path, 'r', encoding='utf-8') as file:
            case_data = yaml.safe_load(file)
            cases.append(case_data['case'])

    return cases



def analyse_case(case_data, case_number):  
    """
    Analyse a single murder case using a zero-shot LLM prompt.

    The model:
    - receives the *complete* case information,
    - is not given any examples,
    - is not constrained by character or role-play rules,
    - does not interact with other agents.

    This function is designed to answer a single question:
    "Is this case solvable based on the information provided?"

    Parameters
    ----------
    case_data : dict
        Structured information describing the murder case.
    case_number : int
        Index of the case (used for logging and reporting).

    Returns
    -------
    str
        A formatted textual analysis generated by the LLM.
    """
    case_name = case_data.get('setting', 'Unknown Case').split('\n')[0]
    
    # -------------------------------------------------
    # Prompt construction
    # -------------------------------------------------
    # The prompt intentionally follows a minimal, analytical style.
    # It provides structure but no examples, ensuring a zero-shot setup.

    prompt = f"""
    Analyse the following murder case carefully and determine who is the most likely killer.
    Consider all evidence, motives, opportunities, and forensic findings. Explain your reasoning step-by-step.

    Case: {case_name}
    Victim: {case_data['victim']['name']}
    Suspects: {', '.join([s['name'] for s in case_data['suspects']])}

    Key Evidence:
    - Crime Scene: {case_data['crime_scene'].get('body_state', 'N/A')}
    - Forensic Findings: {case_data.get('forensic_evidence', {}).get('cause_of_death', 'N/A')}
    - Timeline: {'; '.join(case_data['timeline'])}

    For each suspect, evaluate:
    1. Motive strength
    2. Opportunity (alibis, access)
    3. Physical evidence linking them
    4. Behavioural clues  # British spelling

    After analysing all factors, conclude with the most probable killer and a brief explanation.
    """
    
    # -------------------------------------------------
    # LLM call
    # -------------------------------------------------
    # A low temperature is used to reduce randomness and
    # emphasise analytical consistency over creativity.
    

    url = "https://integrate.api.nvidia.com/v1/chat/completions"

    headers = {
        "Authorization": f"Bearer {API_KEY}",
        "Content-Type": "application/json"
    }

    payload = {
        "model": MODEL_NAME,
        "messages": [
            {"role": "user", "content": prompt}
        ],
        "temperature": 0.3,
        "max_tokens": 1024
    }

    response = requests.post(url, headers=headers, json=payload)

    # print("RAW RESPONSE TEXT:", response.text)

    data = response.json()

    if "choices" not in data:
        raise RuntimeError(f"NVIDIA API request failed: {data}")

    return data["choices"][0]["message"]["content"]



# =================================================
# Result Storage
# =================================================

def save_results_to_file(results, filename=None):
    """
    Save all case analyses to a timestamped text file.

    This output is intended for:
    - human inspection,
    - inclusion as supplementary material,
    - qualitative comparison with multi-agent results.

    Parameters
    ----------
    results : str
        Combined analysis text for all cases.
    filename : str or None
        Optional custom filename.

    Returns
    -------
    str
        The path to the saved file.
    """
    # Ensure output directory exists
    output_dir = "evaluation"
    os.makedirs(output_dir, exist_ok=True)

    if not filename:
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        filename = f"1.0_results_{timestamp}.txt"

    # >>> 修改点：将 filename 放入 evaluation 文件夹 <<<
    output_path = os.path.join(output_dir, filename)

    with open(filename, 'w', encoding='utf-8') as file:
        file.write("MURDER CASE ANALYSIS REPORT\n")
        file.write(f"Generated on: {datetime.now().strftime('%d %B %Y at %H:%M')}\n")
        file.write("="*50 + "\n\n")
        file.write(results)
    
    return filename

# =================================================
# Main Execution
# =================================================

def main():
    """
    Run zero-shot solvability analysis for all cases.

    Each case is analysed independently.
    No information is shared between cases.
    """
    cases = load_case_files()
    all_results = ""
    
    for i, case_data in enumerate(cases, 1):
        print(f"\n{'='*40}")
        print(f"Analysing Case {i}...")
        case_analysis = analyse_case(case_data, i)
        print(case_analysis)
        all_results += case_analysis + "\n" + "="*40 + "\n\n"
    
    # Save all results to file
    output_file = save_results_to_file(all_results)
    print(f"\nAnalysis complete. Results saved to: {output_file}")

# =================================================
# Script Entry Point
# =================================================

